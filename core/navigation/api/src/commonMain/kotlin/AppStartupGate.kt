import androidx.navigation3.runtime.NavKey

/**
 * Проверка, выполняемая один раз при старте приложения.
 *
 * Нужна для сценариев, которые нельзя определить синхронно в [AppDefinition.startRoute],
 * например проверки версии сборки: её результат известен только после сетевого запроса.
 * Гейты регистрируются в Koin и опрашиваются рутовой навигацией при запуске.
 */
interface AppStartupGate {
    /**
     * Проверить условие и вернуть маршрут, на который нужно перейти.
     *
     * @return маршрут для перехода или null, если приложение можно запускать без изменений.
     */
    suspend fun resolveStartupRoute(): NavKey?
}
