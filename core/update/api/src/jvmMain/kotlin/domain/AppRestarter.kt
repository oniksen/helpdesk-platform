package domain

/**
 * Функциональный интерфейс для перезапуска приложения после установки обновления.
 *
 * Реализация должна запустить новый процесс приложения и завершить текущий.
 */
fun interface AppRestarter {
    /** Запускает новый экземпляр приложения и завершает текущий процесс. */
    fun restart()
}
